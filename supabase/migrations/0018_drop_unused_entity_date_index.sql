--  ⚠ طُبِّقت على الإنتاج 2026-07-30 باسم `drop_unused_entity_date_index`.
--
--      idx_sync_rows_entity_date
--        = btree (user_id, (payload->>'date'))
--          WHERE entity IN ('records','prosthetics')
--        ×64 شريحة، إجمالي 1664 كيلوبايت
--
--  ── لماذا: ثلاث طبقات دليل مستقلة ─────────────────────────────────────────
--
--  **1) العدّاد.** 4 مسحات في 82 يوماً و4.2 مليون معاملة. والإحصاءات صُفِّرت
--  2026-05-07 فالنافذة معتبرة — هذا ليس أثر تصفير حديث.
--
--  **2) المستدعون.** لا يخدم إلا `fetch_entity_month` و`get_monthly_summary`،
--  وكلتاهما **صفر استدعاء من عميل** في pg_stat_statements. ولا يخدم
--  `fetch_patient_history` (509 استدعاءً، حيّ): ذاك يرشّح بـ patient_id ويمسح
--  خمسة كيانات، والفهرس جزئي على كيانين فلا ينطبق عليه.
--
--  **3) المخطِّط نفسه — وهذا الحاسم.** EXPLAIN ANALYZE للاستعلام الذي بُني له
--  حرفياً، بهوية إنتاج حقيقية، والفهرس **موجود**:
--
--        Parallel Seq Scan on sync_rows_p61     ← تجاهله تماماً
--        Execution Time: 65.305 ms
--
--  وبإطفاء كل الفهارس قسراً: 52.827 ms — أسرع لا أبطأ. السبب أن الاستعلام
--  يجلب payload كاملاً وانتقائية LIKE على بادئة شهر ضعيفة، فمسح الشريحة
--  المتوازي أرخص من القفز للكومة.
--
--  فالثمن المدفوع — 1.6 م.ب مع تضخيم كتابة على كل إدراج records أو
--  prosthetics، وهما أكثر الكيانات حجماً — يشتري لا شيء قابلاً للقياس.
--
--  ── التحقق بعد الإسقاط ────────────────────────────────────────────────────
--
--      fetch_entity_month('records','2026-06',100)  → 100 صف ✓
--      fetch_patient_history / search_patients_by_phone / find_duplicate_phones → تعمل ✓
--      عزل RLS: user1=149,006 · يرى user2=0 · anon=0 ✓
--      حجم القاعدة: 107 ← 105 م.ب
--
--  ── التراجع: أمر واحد يعيده حرفياً ────────────────────────────────────────
--
--    CREATE INDEX idx_sync_rows_entity_date ON public.sync_rows
--      USING btree (user_id, ((payload ->> 'date'::text)))
--      WHERE (entity = ANY (ARRAY['records'::text, 'prosthetics'::text]));
--
--  إن ظهر يوماً عميل يستدعي دوال التقارير الشهرية بكثافة فأعد إنشاءه — لكن
--  **قِس قبل وبعد**، ولا تفترض أنه سيُستعمل هذه المرة.
-- ============================================================================

DROP INDEX IF EXISTS public.idx_sync_rows_entity_date;
