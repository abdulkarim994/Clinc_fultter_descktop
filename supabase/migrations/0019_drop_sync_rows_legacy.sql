--  أحدث؟ حُكّم مقارنان مستقلان:
--
--      hlc_is_newer (مقارن المحرّك نفسه) : sync_rows أحدث في 30/30
--      updated_at                        : sync_rows أحدث في 30/30
--
--  صفر حالة يكون فيها القديم أحدث، وصفر التباس. الجدول بائت بالكامل.
--
--  ── الجولة الثانية: بعد تنظيف بيانات الاختبار ────────────────────────────
--
--  الـ146 صفاً **كلها** تخص حسابات حُذفت بياناتها قصداً في التنظيف نفسه،
--  و**صفر** منها يخص أياً من الحسابين المستبقَيين.
--
--  ── ولا مستهلك واحد ───────────────────────────────────────────────────────
--
--  فُحص `pg_proc` و`pg_views` و`pg_rules`: لا دالة ولا عرض ولا قاعدة تشير
--  إليه — فقط مُطلِق `trg_sync_rows_seq` على الجدول ذاته. و`pg_stat_statements`
--  على مدى 82 يوماً لم يسجّل عبارة تطبيق واحدة تلمسه؛ العبارة الوحيدة كانت
--  تعليق مهاجرة التقسيم أعلاه.
--
--  ── لا تراجع ──────────────────────────────────────────────────────────────
--
--  هذا إسقاط جدول ببيانات. لا يُستعاد إلا من نسخة احتياطية للحظة ما قبله.
-- ============================================================================

DROP TABLE IF EXISTS public.sync_rows_legacy;
