-- ============================================================================
--  م68/دفعة ثانٍ-أ — إخراج شرائح sync_rows من سطح PostgREST
-- ============================================================================
--
--  ⚠ طُبِّقت على الإنتاج 2026-07-30 باسم
--    `revoke_api_grants_on_sync_rows_partitions` (20260730024102).
--
--  ما رُصد
--  ───────
--  شرائح `sync_rows` الأربع والستون تعيش في مخطط `public`، وكانت تحمل
--  منحة SELECT للدورين `anon` و`authenticated`. PostgREST يكشف كل جدول
--  في `public`، فكان لكلٍّ منها نقطة نهاية صالحة:
--
--      GET /rest/v1/sync_rows_p61
--
--  هل كان تسريباً؟ **لا** — والتحقق العملي هو ما حسم هذا لا الافتراض:
--
--      قراءة sync_rows_p61 مباشرةً بهوية **صاحب البيانات نفسه** : 0 صفاً
--      الجدول ذاته بصلاحية تجاوز RLS                            : 149,006 صفاً
--
--  السبب أن الشرائح تُفعِّل RLS بلا سياسات، و«RLS مفعَّل بلا سياسة» في
--  PostgreSQL يعني **منعاً كاملاً** لا سماحاً. فالسلوك كان مغلقاً افتراضياً
--  وهو الوضع الصحيح.
--
--  فلماذا التغيير إذن
--  ──────────────────
--  لأن الأمان كان معلَّقاً على طبقة واحدة. لو عُطِّل RLS على شريحة يوماً —
--  بمهاجرة لاحقة، أو باستعادة نسخة احتياطية، أو بخطأ يدوي — لصار الجدول
--  مقروءاً بالكامل عبر REST بلا سياسة واحدة تعترضه، ولمرّ ذلك صامتاً لأن
--  لا شيء في المخطط يشير إلى الخطر. سحب المنحة يجعل الفشل مغلقاً على
--  طبقتين مستقلتين.
--
--  لماذا هذا آمن على التطبيق
--  ─────────────────────────
--  PostgreSQL **لا يفحص صلاحيات الشرائح** عند الوصول عبر الجدول الأب
--  المقسَّم — الفحص على الأب وحده. وقد اختُبر هذا على p61 وحدها قبل
--  التعميم بدل الاكتفاء بالتوثيق:
--
--      بعد سحب المنحة عن p61 فقط:
--        SELECT ... FROM sync_rows           → 149,006  (سليم)
--        SELECT ... FROM sync_rows_p61       → permission denied
--
--  ثم عُمِّم على الـ64. ودوال RPC (apply_changes / pull_changes) تعمل
--  بـ SECURITY DEFINER بهوية المالك فلا تتأثر بمنح الدورين أصلاً.
--
--  `service_role` غير مشمول عمداً — يحتاجه العمل الإداري والصيانة.
--
--  التحقق بعد التطبيق
--  ──────────────────
--    شرائح ما زالت مكشوفة للـ API : 0
--    user1 عبر الأب               : 149,006
--    user1 يرى صفوف user2         : 0
--    user2 عبر الأب               : 325
--    anon                          : 0
--    pull_changes RPC              : يعمل
--    مجموع الصفوف                  : 149,892  (لم يتغيّر)
-- ============================================================================

DO $$
DECLARE r record;
BEGIN
  FOR r IN
    SELECT c.relname
    FROM pg_class c
    JOIN pg_inherits i ON i.inhrelid = c.oid
    WHERE i.inhparent = 'public.sync_rows'::regclass
      AND c.relkind = 'r'
  LOOP
    EXECUTE format('REVOKE ALL ON public.%I FROM authenticated, anon', r.relname);
  END LOOP;
END $$;
