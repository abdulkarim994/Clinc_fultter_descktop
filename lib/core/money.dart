/// ============================================================================
///  م85 — النقود بالقروش الصحيحة: حسابٌ لا ينجرف أبداً
/// ============================================================================
///
///  المشكلة بلغة العيادة
///  ────────────────────
///  الحاسوب يخزّن الأرقام الصحيحة بدقّة مطلقة، لكنه يخزّن الأرقام بفواصل
///  (10.5) **تقريباً** (10.4999999…). في جمعٍ واحد لا يظهر شيء، لكن في
///  تقريرٍ يجمع آلاف الأقساط والدفعات والنِّسب قد يظهر يوماً **فرقُ قرشٍ**
///  لا يُفسَّر — وهو ما يهزّ ثقة المحاسب في منتجٍ يُباع لعيادات.
///
///  العلاج
///  ──────
///  الحساب الداخلي كله يجري على **قروشٍ صحيحة** (int): «10.5 ديناراً» تصير
///  «1050 قرشاً»، فالجمع والطرح والنسب تجري على أعداد صحيحة **لا تنجرف
///  أبداً**، ثم تُقسَم على 100 عند العرض فقط.
///
///  ⚠ لماذا لا نغيّر التخزين والإرسال
///  ─────────────────────────────────
///  هذا التطبيق يشارك صيغة البيانات (مبالغ عشرية) مع خلفية Supabase ومع
///  نسخة الويب Vue. فتغييرُ وحدة **الإرسال** إلى قروش بلا حقل إصدار في
///  البروتوكول يجعل نسخةً قديمة تقرأ 1050 على أنها 1050 ديناراً — فسادُ
///  مبلغٍ بمعامل 100 بين الأجهزة. ولذلك: **الحساب بالقروش، والتخزين والإرسال
///  يبقيان بالدينار العشري كما هو** — لكن مضبوطَين على القرش تماماً عند كل
///  كتابة عبر [quantize]، فلا غبار دون القرش يُخزَّن أبداً.
library;

import 'utils/js_compat.dart' show jsNumOr0;

/// عدد القروش في وحدة العملة. ثنائيُّ المنزلة العشرية معيارُ العملات هنا.
const int kMinorPerUnit = 100;

/// دينار عشري ⇒ قروش صحيحة. **نقطة التحويل الوحيدة** — كل شيء يمرّ بها.
///
/// يقبل أي مدخل يفهمه [jsNumOr0] (عدد، نصّ، أرقام عربية) ويقرّبه لأقرب
/// قرش. `round()` لا `floor` كي يطابق تقريب نقاط التقسيم القائمة
/// (`(x*100).round()/100`) حرفياً — فالسلوك مكافئ لا متغيّر.
int toCents(Object? currency) => (jsNumOr0(currency) * kMinorPerUnit).round();

/// قروش صحيحة ⇒ دينار عشري للعرض والتخزين والإرسال.
///
/// يعيد `int` حين يكون المبلغ دنانير كاملة كي يبقى تمثيل JSON مطابقاً
/// للسابق (`5` لا `5.0`)، وإلا `double`. هذا يحفظ تكافؤ حمولة المزامنة.
num fromCents(int cents) =>
    cents % kMinorPerUnit == 0 ? cents ~/ kMinorPerUnit : cents / kMinorPerUnit;

/// يضبط مبلغاً عشرياً على القرش: يحوّله قروشاً ثم يعيده عشرياً. يُستعمَل
/// عند **حدود الكتابة** فلا يُخزَّن غبارٌ دون القرش أبداً. عديم الأثر على
/// مبلغٍ مضبوطٍ أصلاً.
num quantize(Object? currency) => fromCents(toCents(currency));

/// يجمع حقلاً من صفوفٍ **بالقروش الصحيحة** ثم يعيد الدينار العشري.
///
/// هذا قلب الإصلاح: `fold` على `double` يراكم غبار التقريب عبر آلاف
/// الصفوف؛ والجمع بالقروش الصحيحة **يستحيل أن ينجرف**.
num sumMoney(Iterable<Map<String, Object?>> rows, String key) {
  var cents = 0;
  for (final r in rows) {
    cents += toCents(r[key]);
  }
  return fromCents(cents);
}

/// نصيبٌ بنسبةٍ مئوية، محسوبٌ بالقروش الصحيحة ومقرَّبٌ لأقرب قرش.
///
/// `baseCents * pct` عددٌ صحيح كبير (‏bigint داخلياً في Dart للأعداد فوق
/// 2^53؟ لا — لكن المبالغ العيادية أصغر من ذلك بمراحل)، والقسمة على 100
/// بتقريبٍ نصفيّ صريح. لا كسورَ وسيطة تنجرف.
int shareCents(int baseCents, num pct) {
  final scaled = baseCents * pct; // pct قد تكون عشرية (40.5%)
  return (scaled / 100).round();
}
