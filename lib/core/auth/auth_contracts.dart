/// ============================================================================
///  م82 — عقود المصادقة: كسر الدورة بين الطبقتين
/// ============================================================================
///
///  العلة
///  ─────
///  `AuthService` و`AuthUser` كانا يعيشان في `features/auth/`، بينما
///  `data/cloud/supabase_auth_service.dart` **ينفّذ** الواجهة — فيستورد
///  من طبقة الميزات إلى أعلى. وهي **الدورة الحقيقية الوحيدة** في المشروع:
///  اتجاهُ الاعتماد يجب أن يكون من الميزات إلى البيانات لا العكس.
///
///  الأثر العملي لا النظري: لا تستطيع بناء أو اختبار طبقة البيانات
///  مستقلّةً، لأنها تسحب معها طبقة الميزات بكاملها.
///
///  الحل
///  ────
///  العقد ينتقل إلى `core/` — الطبقة المحايدة التي تستورد منها الطبقتان
///  ولا تستورد من أيّهما. والمنفّذون يبقون في مكانهم: `LocalAuthService`
///  في الميزات، و`SupabaseAuthService` في البيانات، وكلاهما يستورد **نزولاً**.
///
///  التوافق: `features/auth/auth_service.dart` يُعيد تصدير هذه الرموز،
///  فكل مستورد قائم يعمل بلا تغيير سطر واحد.
library;

class AuthUser {
  const AuthUser({required this.uid, required this.email, this.displayName});

  final String uid;
  final String email;

  /// م88 — الاسم المعروض من مزوّد خارجي (Google) لرسالة الترحيب. اختياريّ
  /// وإضافيّ: دخولُ البريد/كلمة المرور يتركه `null` فلا يتغيّر شيء قائم.
  final String? displayName;
}

abstract interface class AuthService {
  AuthUser? restoreSession();
  Future<AuthUser> login(String email, String password, {bool remember});
  Future<void> register(String email, String password);
  Future<void> logout();

  /// م180/د — «نسيت كلمة المرور»: يرسل بريد إعادة التعيين. الوضع المحلي
  /// (بلا سحابة) يرمي [AuthException] برسالة عربية صريحة — لا صمت.
  Future<void> sendPasswordReset(String email);

  /// م186 — إتمام الاستعادة **داخل التطبيق**: رمز التحقق من البريد +
  /// كلمة المرور الجديدة. (رابط البريد القديم كان يوجّه لصفحة معطوبة —
  /// فصار التدفق رمزاً يُدخل في التطبيق نفسه، هاتفاً وكمبيوتر، بلا
  /// متصفح ولا صفحات وسيطة.) الوضع المحلي يرمي رسالة عربية صريحة.
  Future<void> confirmPasswordReset({
    required String email,
    required String code,
    required String newPassword,
  });
}

/// ============================================================================
///  م88 — جسر جلسة الحزمة الرسمية (supabase_flutter)
/// ============================================================================
///
///  لماذا جسرٌ في `core` لا استيرادٌ مباشر للحزمة في طبقة البيانات
///  ──────────────────────────────────────────────────────────────
///  دخولُ Google يُنشئ جلسته داخل الحزمة الرسمية (تدفّق PKCE، تخزينٌ آمن،
///  تجديدٌ تلقائي). وطبقتا المزامنة وR2 تطلبان «رمزَ وصولٍ صالحاً» من
///  `SupabaseAuthService` — فيلزم أن ترى الخدمةُ جلسةَ الحزمة **دون** أن
///  تعتمد طبقةُ البيانات على حزمة واجهةٍ كاملة، ودون أن تحتاج الاختباراتُ
///  منصةً حقيقية. العقدُ هنا صغيرٌ عمداً: لقطةُ هوية، رمزٌ طازج، تجديدٌ
///  قسري (مسار 401)، وخروج.
///
///  ⚠ قاعدةُ «محرّكِ جلسةٍ واحد»: رمزُ تحديث GoTrue **يُستهلك بالاستعمال**
///  (تدوير). محرّكان يجدّدان نفس الجلسة = سباقٌ يقتلها. فجلسة Google
///  يديرها **الجسرُ وحده** (الحزمة)، وجلسة كلمة المرور يديرها **المحرّك
///  القائم وحده** — ودخولُ أيٍّ منهما يمسح جلسةَ الآخر.
class SdkSessionInfo {
  const SdkSessionInfo({
    required this.uid,
    required this.email,
    this.displayName,
    this.avatarUrl,
  });

  final String uid;
  final String email;
  final String? displayName;
  final String? avatarUrl;
}

abstract interface class SdkSessionBridge {
  /// لقطة الجلسة الحالية — قراءةٌ متزامنة (بعد اكتمال تهيئة الحزمة عند
  /// الإقلاع)، و`null` حين لا جلسةَ للحزمة.
  SdkSessionInfo? current();

  /// رمز وصولٍ صالح للنقل: يجدّد عند قرب الانتهاء ويعيد الحالي عند فشل
  /// الشبكة (الخادم سيردّ 401 فيُعاد عبر [forceRefresh] — نفس عقد المحرّك
  /// القائم حرفياً).
  Future<String?> freshAccessToken();

  /// مسار 401: تجديدٌ فوري قسري. `null` عند التعذّر.
  Future<String?> forceRefresh();

  /// خروجٌ لا يرمي أبداً: التنظيف المحلي مضمونٌ ولو فشل إبطال الخادم
  /// (أوفلاين) — فشلُ الشبكة يُبتلع بعد التنظيف.
  Future<void> signOut();
}

final _emailRe = RegExp(r'^[^\s@]+@[^\s@]+\.[^\s@]+$');

/// تحقّق المدخلات — رسائل عربية جاهزة للعرض.
String? validateCredentials(String email, String password) {
  if (email.trim().isEmpty || !_emailRe.hasMatch(email.trim())) {
    return 'يرجى إدخال بريد إلكتروني صحيح';
  }
  // م68 — رُفع الحد الأدنى من ستة إلى ثمانية. ستةُ محارف مساحةٌ تُستنفد
  // بالبحث الشامل في زمن تافه؛ والثمانية حدٌّ أدنى معقول لا يُرهق مستخدمي
  // العيادة. (الطول وحده — لا تركيبة معقدة تدفع الطاقم لكتابة الكلمة على
  // ورقة، فيصير التعقيد ضرراً صافياً.)
  if (password.length < 8) {
    return 'كلمة المرور يجب أن تكون 8 أحرف على الأقل';
  }
  return null;
}
