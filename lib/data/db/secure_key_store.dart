/// ============================================================================
///  م83 — مخزن مفتاح القاعدة في مخزن أسرار النظام
/// ============================================================================
///
///  لماذا لا يُكتب المفتاح في ملف
///  ────────────────────────────
///  تشفيرُ القاعدة ومفتاحُها في ملف بجوارها ليس تشفيراً بل تعقيد: من يأخذ
///  الجهاز يأخذ الاثنين معاً. المفتاح يعيش في مخزن النظام:
///
///    • أندرويد — Keystore: المفتاح الملفوف بـRSA-OAEP والبيانات بـAES-GCM،
///      والفكّ يتطلّب جهازاً مفتوحاً. الأجهزة الحديثة تحفظه في عتاد آمن.
///    • ويندوز  — DPAPI: مربوطٌ بحساب المستخدم، فمستخدمٌ آخر على الجهاز
///      نفسه لا يفكّه، ونسخُ الملف إلى حاسوب آخر لا يفيد.
///
///  ⚠ الإعداد الأخطر في الحزمة: `resetOnError`
///  ──────────────────────────────────────────
///  افتراضُه **`true`**، ومعناه في الشيفرة الأصيلة حرفياً: «أخفق الفكّ ⇒
///  احذف كل البيانات للتعافي». وهو تصرّفٌ معقول لرمز جلسة يُعاد جلبه،
///  و**كارثة مطلقة** لمفتاح قاعدة: عطلٌ عابر في Keystore — بعد تحديث نظام،
///  أو استعادة نسخة، أو تغيّر بصمة التوقيع — يمحو المفتاح، فتصير قاعدة
///  العيادة كتلةً مشفَّرة لا يفتحها أحد، **بلا رسالة ولا رجعة**.
///
///  ولذلك هنا `resetOnError: false`: نُفضّل خطأً صريحاً يُبلَّغ ويُعالَج على
///  حذفٍ صامت لا شفاء منه. والمقابل أن الفشل يظهر للمستخدم بدل أن يُخفى —
///  وهذا هو المطلوب بالضبط حين يكون البديل فقدان البيانات.
///
///  و`migrateOnAlgorithmChange: true` يُبقي المفتاح حياً حين تُحدَّث الحزمة
///  خوارزمياتها بدل أن يُعدّه غير قابل للفكّ.
///
///  حدود ما يمكن التحقق منه
///  ───────────────────────
///  هذا الملف يعتمد على منصّة حقيقية، فلا يُختبر في بيئة بلا جهاز. المُختبَر
///  هو **العقد** الذي ينفّذه ([DbKeyStore])، ودورة الحياة كلها فوقه عبر
///  [MemoryDbKeyStore]. والمكتوب هنا رقيقٌ عمداً: كل منطق قابل للاختبار
///  يعيش في `db_key.dart` لا هنا.
library;

import 'package:flutter_secure_storage/flutter_secure_storage.dart';

import 'db_key.dart';

/// خيارات أندرويد — الافتراضات القوية للحزمة **عدا** الحذف عند الخطأ.
const AndroidOptions _kAndroid = AndroidOptions(
  // ⚠ لا تُعِدها إلى true: تعني «احذف المفتاح عند أول خطأ فكّ»، وحذفُ
  // مفتاح القاعدة = فقدان العيادة بلا استرجاع.
  resetOnError: false,
  // تُحافظ على المفتاح عبر ترقيات الحزمة بدل عدّه تالفاً.
  migrateOnAlgorithmChange: true,
);

/// خيارات ويندوز — DPAPI بلا توافق خلفيّ (لا بيانات قديمة تُهاجَر).
const WindowsOptions _kWindows = WindowsOptions(
  useBackwardCompatibility: false,
);

const FlutterSecureStorage _kStorage = FlutterSecureStorage(
  aOptions: _kAndroid,
  wOptions: _kWindows,
);

/// تنفيذ الإنتاج لـ[DbKeyStore]: Keystore على أندرويد وDPAPI على ويندوز.
class SecureDbKeyStore implements DbKeyStore {
  const SecureDbKeyStore([FlutterSecureStorage? storage])
      : _storage = storage ?? _kStorage;

  final FlutterSecureStorage _storage;

  @override
  Future<String?> read() => _storage.read(key: kDbKeyName);

  @override
  Future<void> write(String key) =>
      _storage.write(key: kDbKeyName, value: key);

  /// الحذف فعلٌ صريح لا يُستدعى في المسار العادي أبداً.
  ///
  /// موجودٌ لإتمام العقد ولحالة «إعادة الضبط الكاملة» التي يطلبها المالك
  /// عامداً. واستدعاؤه فوق قاعدة قائمة يُفقدها — ولذلك لا يناديه شيء في
  /// مسار الإقلاع.
  @override
  Future<void> delete() => _storage.delete(key: kDbKeyName);
}
