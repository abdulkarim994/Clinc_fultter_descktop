///  م83 — مفتاح تشفير القاعدة: توليده وحفظه ودورة حياته
/// ============================================================================
///
///  العلة
///  ─────
///  كانت القاعدة تُفتح بـ`sqlite3.open(path)` بلا مفتاح، فملفُ المرضى نصٌّ
///  مقروء على القرص: الأسماء والهواتف والتاريخ المرضي وصور الأشعة. ولوحٌ
///  مسروق أو حاسوب ويندوز بمستخدم آخر = **كل شيء مقروء**، وكلمة مرور
///  التطبيق تحمي الشاشة لا الملف.
///
///  أين يعيش المفتاح — وهذا هو السؤال الحقيقي
///  ──────────────────────────────────────────
///  التشفير بلا حفظٍ آمن للمفتاح مسرحية: مفتاحٌ في ملف بجوار القاعدة يعني
///  أن من يأخذ أحدهما يأخذ الآخر. ولذلك [DbKeyStore] **واجهة** لا تنفيذاً
///  واحداً:
///
///    • [SecureDbKeyStore]  — الإنتاج. مخزن النظام: Keystore على أندرويد
///      وDPAPI على ويندوز. المفتاح لا يغادره ولا يُقرأ بلا فتح الجهاز.
///    • [MemoryDbKeyStore]  — الاختبارات. لا قرص ولا منصّة.
///
///  ⚠ صدقٌ في التوصيف: التنفيذ الآمن يعتمد على منصّة حقيقية، ولا يمكن
///  التحقق منه في بيئة اختبار بلا جهاز. المُتحقَّق منه هنا هو **كل ما
///  عداه**: التوليد، والدورة، والترحيل، والفشل المغلق.
///
///  فقدان المفتاح = فقدان القاعدة
///  ─────────────────────────────
///  هذه ليست علّة بل **تعريف التشفير**. ولذلك لا يُولَّد مفتاح جديد فوق
///  قاعدة قائمة أبداً — [resolveKey] تُميّز «أول تشغيل» من «مفتاح مفقود»،
///  والثانية تُبلَّغ خطأً صريحاً بدل إنشاء قاعدة فارغة تبدو كأن البيانات
///  تبخّرت.
library;

import 'dart:convert';
import 'dart:io';
import 'dart:math';

/// طول المفتاح: 32 بايتاً (256 بت) — ما يتوقّعه SQLCipher لمفتاح خام.
const int kDbKeyBytes = 32;

/// اسم المفتاح في مخزن النظام.
const String kDbKeyName = 'dental.db.key.v1';

/// علامة على القرص تقول «هذه القاعدة مشفَّرة».
///
/// ⚠ **تشخيصية لا حاكمة.** كانت في أول تصميم هي الفاصل بين «أول تشغيل»
/// و«مفتاح مفقود»، فكشفت المراجعة أن غيابها يُتلف قاعدةً سليمة ووجودها
/// وحدها يُقفل تطبيقاً بلا بيانات. الحاكم الآن حالةُ ملفّي القاعدة والخزنة
/// (انظر [resolveKey])، وهذه تبقى لأنها تُفيد في التشخيص وقراءةِ التاريخ.
const String kCipherMarkerFile = '.db_encrypted';

abstract interface class DbKeyStore {
  Future<String?> read();
  Future<void> write(String key);
  Future<void> delete();
}

/// مخزن الاختبارات — لا قرص ولا منصّة.
class MemoryDbKeyStore implements DbKeyStore {
  String? _v;
  @override
  Future<String?> read() async => _v;
  @override
  Future<void> write(String key) async => _v = key;
  @override
  Future<void> delete() async => _v = null;
}

/// يولّد مفتاحاً عشوائياً آمناً بصيغة hex التي يقبلها `PRAGMA key`.
///
/// `Random.secure()` يستمدّ من مولّد النظام. والصيغة `x'...'` تجعل
/// SQLCipher يستعمل البايتات **كما هي** بلا اشتقاق — وهو المطلوب لمفتاح
/// عشوائي كامل الإنتروبيا (الاشتقاق لكلمات المرور البشرية لا للمفاتيح).
String generateDbKey([Random? rng]) {
  final r = rng ?? Random.secure();
  final bytes = List<int>.generate(kDbKeyBytes, (_) => r.nextInt(256));
  return bytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
}

/// صيغة `PRAGMA key` لمفتاح خام hex.
///
/// ⚠ **الاقتباس المزدوج جزءٌ من الصيغة لا تجميل.** SQLCipher يتوقّع القيمة
/// سلسلةً نصّية محتواها `x'<hex>'`، فالناتج الصحيح:
///
///     PRAGMA key = "x'a1b2...'";
///
/// وبلا الاقتباس الخارجي يرمي المحلّل `syntax error` — لأن `x'...'` وحدها
/// حرفيةُ بايتات (blob) لا سلسلة. (رُصد بالتشغيل: أول صياغة بلا اقتباس
/// أسقطت كل فتح مشفَّر.)
///
/// والصيغة الخام تعني أن SQLCipher يستعمل البايتات **كما هي بلا اشتقاق**،
/// وهو الصواب لمفتاح عشوائي كامل الإنتروبيا — الاشتقاق لكلمات المرور
/// البشرية لا للمفاتيح المولَّدة.
String pragmaKeyLiteral(String hexKey) => '"x\'$hexKey\'"';

class DbKeyResolution {
  const DbKeyResolution({required this.key, required this.isFirstRun});

  final String key;

  /// أول تشغيل ⇒ القاعدة ستُنشأ مشفَّرة، أو القاعدة السادة تنتظر الترحيل.
  final bool isFirstRun;
}

/// تُرمى حين تكون القاعدة مشفَّرة والمفتاح مفقوداً.
///
/// **لا يُولَّد مفتاح جديد في هذه الحالة**: ذلك يُنشئ قاعدة فارغة تبدو كأن
/// بيانات العيادة تبخّرت، وهو أسوأ فشل ممكن — صامتٌ ولا رجعة فيه. الخطأ
/// الصريح يُبقي الملف سليماً ويترك للمالك فرصة استعادة المفتاح أو النسخة.
class DbKeyMissingException implements Exception {
  DbKeyMissingException(this.dbPath);
  final String dbPath;
  @override
  String toString() =>
      'مفتاح تشفير القاعدة مفقود بينما القاعدة مشفَّرة ($dbPath). '
      'لم يُولَّد مفتاح جديد عمداً — ذلك يُنشئ قاعدة فارغة. '
      'استعد المفتاح من نسخة الجهاز الاحتياطية، أو استرجع من السحابة بحساب جديد.';
}

File cipherMarker(String dbDir) => File('$dbDir/$kCipherMarkerFile');

/// صيغة المفتاح المقبولة: 64 محرفاً hex بالضبط (32 بايتاً).
final RegExp _kHexKey = RegExp(r'^[0-9a-fA-F]{64}$');

/// يحسم المفتاح المستعمل لهذه القاعدة.
///
/// [encryptedDataExists] هو **الدليل**: هل على القرص بياناتٌ مشفَّرة فعلاً؟
///
/// ولماذا دليلٌ مُمرَّر لا علامةٌ تُقرأ هنا — درسٌ من مراجعة:
/// كانت الدالة تقرأ ملف العلامة بنفسها، فانكشف عطلان متقابلان:
///   • العلامة محذوفة (تنظيف مجلد، استعادة ناقصة، أو إخفاق كتابتها
///     المبتلَع) والقاعدة مشفَّرة ⇒ تُعدّ «أول تشغيل»، فيُولَّد مفتاح
///     **جديد يُكتب فوق القديم** ويصير فقدُ البيانات نهائياً بدل أن يكون
///     قابلاً للإصلاح.
///   • العلامة باقية ولا قاعدة ولا خزنة ⇒ رفضٌ أبديّ للإقلاع حمايةً
///     لبيانات **لا وجود لها**، ولا مخرج إلا حذف ملف مخفيّ يدوياً.
///
/// وملفُ القاعدة نفسه دليلٌ لا يكذب: رأسُه يقول أمشفَّرٌ هو أم لا. فصار
/// الحسم على الملفات، والعلامة تشخيصاً لا حاكماً.
///
/// الحالات:
///   ١) مفتاح موجود                      ⇒ يُستعمل.
///   ٢) لا مفتاح ولا بيانات مشفَّرة       ⇒ أول تشغيل: يُولَّد ويُحفظ.
///   ٣) لا مفتاح **مع** بيانات مشفَّرة    ⇒ [DbKeyMissingException].
Future<DbKeyResolution> resolveKey(
  DbKeyStore store, {
  required bool encryptedDataExists,
  String dbDir = '',
}) async {
  final existing = await store.read();
  if (existing != null && existing.isNotEmpty) {
    if (!_kHexKey.hasMatch(existing)) {
      // مفتاحٌ تالف أو مُلوَّث. لا يُستعمل ولا يُستبدل: استعماله يُفشل
      // الفتح بلا تفسير، واستبداله يُتلف قاعدةً ما زالت سليمة.
      throw DbKeyMissingException(
          '$dbDir (المفتاح المخزَّن ليس 64 محرفاً hex — تالفٌ أو مُبدَّل)');
    }
    return DbKeyResolution(key: existing, isFirstRun: false);
  }
  if (encryptedDataExists) {
    throw DbKeyMissingException(dbDir);
  }
  final fresh = generateDbKey();
  await store.write(fresh);
  return DbKeyResolution(key: fresh, isFirstRun: true);
}

/// تضع العلامة بعد نجاح أول فتح/ترحيل مشفَّر.
void markEncrypted(String dbDir) {
  try {
    final f = cipherMarker(dbDir);
    if (!f.existsSync()) f.writeAsStringSync(jsonEncode({'v': 1}));
  } catch (_) {/* أفضل جهد — غيابها يعني إعادة توليد لا فقداً */}
}

bool isMarkedEncrypted(String dbDir) => cipherMarker(dbDir).existsSync();
