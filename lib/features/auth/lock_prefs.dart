/// ============================================================================
///  م87 — تفضيلات القفل: محليّة لكل جهاز لا مُزامَنة
/// ============================================================================
///
///  لماذا محليّة لا في `app.config` المُزامَن
///  ─────────────────────────────────────────
///  «عطِّل القفل» قرارُ **ثقةٍ بجهازٍ بعينه** — حاسوب العيادة المقفول في
///  غرفة الطبيب غير اللوح المتنقّل عند الاستقبال. ولو خُزّن في الإعداد
///  المُزامَن لانتشر «القفل معطَّل» إلى كل الأجهزة، فيُلغى الأمان حيث هو
///  ألزم. والبصمة أصلاً مربوطةٌ بعتاد الجهاز، فلا معنى لمزامنتها.
///
///  فتُخزَّن في `sync_meta` المحلية بمفتاح المالك — نفس مكان مُتحقِّق القفل
///  (م79) ونفس ضماناته: لا تغادر الجهاز، ولا تدخل حمولة المزامنة.
///
///  الافتراضات (م97 — قرار المالك)
///  ──────────────────────────────
///    • قفل الإقلاع: **معطَّل** افتراضاً (الغياب = معطَّل). كان مُفعَّلاً
///      (م87)، وقلبه المالك في م97: القفل خدمةٌ يفعّلها من يريدها، وشرطُ
///      تفعيلها تعيينُ «رمز قفل التطبيق» أولاً (بوابة الإعدادات) — فلا
///      يصل أحدٌ إلى قفلٍ لا مفتاح له.
///    • البصمة: **معطَّلة** افتراضاً، وتفعيلُها مشروطٌ بالرمز نفسه —
///      فالبصمة بوابةُ تسريعٍ فوق الرمز لا بديلاً عنه.
library;

import '../../data/db/local_db.dart';
import '../../data/sync/db_sync.dart' show getMetaValue, setMetaValue;

const String _kLockOnStartKey = 'auth.lock_on_start';
const String _kBiometricKey = 'auth.biometric_enabled';

String _owner(LocalDb db) => db.getOwnerUid() ?? '';

/// هل يبدأ التطبيق مقفلاً على الإقلاع البارد؟ الغياب ⇒ **لا** (م97:
/// معطَّل حتى يفعّله المالك بعد تعيين رمزه).
bool lockOnStartEnabled(LocalDb db) {
  final v = getMetaValue(db, _kLockOnStartKey);
  return v != null && '$v' == '1';
}

void setLockOnStart(LocalDb db, bool enabled) {
  try {
    setMetaValue(db, _kLockOnStartKey, enabled ? '1' : '0', _owner(db));
  } catch (_) {/* أفضل جهد */}
}

/// هل فعّل المالك دخول البصمة على هذا الجهاز؟ الغياب ⇒ لا (اختياريّ).
bool biometricEnabled(LocalDb db) => '${getMetaValue(db, _kBiometricKey) ?? ''}' == '1';

void setBiometricEnabled(LocalDb db, bool enabled) {
  try {
    setMetaValue(db, _kBiometricKey, enabled ? '1' : '0', _owner(db));
  } catch (_) {/* أفضل جهد */}
}
